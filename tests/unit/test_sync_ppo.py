"""Regression tests for synchronized PPO collection and exact evaluator records."""

# pylint: disable=import-error,protected-access

import asyncio

import numpy as np
import pytest

from pyrl_trainer.agent import Transition
from pyrl_trainer.config import Config
from pyrl_trainer.sensor_contract import SensorContract
from pyrl_trainer.sync_ppo import (
    SynchronousActorClient,
    SynchronousSharedState,
    _coherent_policy_version,
    _write_exact_best_metadata,
    apply_stable_learning_rate_default,
    enforce_optimizer_learning_rate,
    restore_exact_best_metadata,
    synchronous_learner_loop,
)

pytestmark = pytest.mark.unit


def _config(tmp_path=None, **kwargs) -> Config:
    values = {
        "actors": 2,
        "batch_size": 4,
        "minibatch": 2,
        "epochs": 2,
        "net_hidden": 8,
        "net_layers": 1,
        "train_device": "cpu",
        "infer_device": "cpu",
        "turn_std": 0.2,
        "lr": 1e-8,
        "save_every_updates": 0,
        "log_every_seconds": 3600.0,
    }
    if tmp_path is not None:
        values["ckpt_dir"] = str(tmp_path)
    values.update(kwargs)
    return Config(**values)


def _state(cfg: Config) -> SynchronousSharedState:
    return SynchronousSharedState(
        obs_dim=2,
        cfg=cfg,
        sensor_contract=SensorContract("v3", ("a", "b")),
    )


def _transition(state: SynchronousSharedState, reward: float = 0.1) -> Transition:
    obs = np.zeros(2, dtype=np.float32)
    turn, boost, logp, value, latent = state.act(obs, turn_std=state.cfg.turn_std)
    return Transition(
        obs=obs,
        action_turn=turn,
        turn_latent=latent,
        action_boost=boost,
        logp=logp,
        value=value,
        reward=reward,
        done=0.0,
        policy_version=state.published_policy_version,
    )


def test_autogenerated_legacy_learning_rate_migrates_to_stable_default(tmp_path):
    """Existing generated configs get the safer PPO rate without user intervention."""
    path = tmp_path / "config.toml"
    path.write_text(
        "# Slither trainer configuration\n"
        "# Auto-generated because it was missing.\n\n"
        "[training]\n"
        "lr = 0.0003\n",
        encoding="utf-8",
    )
    cfg = Config(lr=3e-4)

    apply_stable_learning_rate_default(cfg, str(path))

    assert cfg.lr == pytest.approx(1e-4)
    assert "lr = 0.0001" in path.read_text(encoding="utf-8")


def test_explicit_learning_rate_environment_override_is_preserved(tmp_path, monkeypatch):
    """A deliberate SLITHER_LR setting remains authoritative."""
    path = tmp_path / "config.toml"
    path.write_text(
        "# Auto-generated because it was missing.\n[training]\nlr = 0.0003\n",
        encoding="utf-8",
    )
    monkeypatch.setenv("SLITHER_LR", "0.0003")
    cfg = Config(lr=3e-4)

    apply_stable_learning_rate_default(cfg, str(path))

    assert cfg.lr == pytest.approx(3e-4)
    assert "lr = 0.0003" in path.read_text(encoding="utf-8")


def test_resumed_optimizer_uses_current_configured_learning_rate():
    """Checkpoint Adam metadata cannot silently restore the old aggressive rate."""
    cfg = _config(lr=1e-4)
    state = _state(cfg)
    state.optimizer.param_groups[0]["lr"] = 3e-4

    enforce_optimizer_learning_rate(state)

    assert state.optimizer.param_groups[0]["lr"] == pytest.approx(1e-4)


def test_legacy_best_does_not_block_new_exact_evaluator_leaderboard(tmp_path):
    """A historical training-actor record is retained separately from exact best."""
    cfg = _config(tmp_path)
    state = _state(cfg)
    state.best_lifetime_ticks = 17996
    state.best_episode_return = 1.3

    restore_exact_best_metadata(cfg, state)

    assert state.legacy_best_lifetime_ticks == 17996
    assert state.best_lifetime_ticks == 0
    assert state.best_episode_return == float("-inf")

    snapshot, _model = state.begin_evaluation_policy()
    state.record_episode(
        0.46,
        4642,
        policy_snapshot=snapshot,
        include_runtime_stats=False,
    )
    assert state.best_checkpoint_pending
    _write_exact_best_metadata(cfg, state)

    resumed = _state(cfg)
    resumed.best_lifetime_ticks = 17996
    resumed.best_episode_return = 1.3
    restore_exact_best_metadata(cfg, resumed)

    assert resumed.legacy_best_lifetime_ticks == 17996
    assert resumed.best_lifetime_ticks == 4642
    assert resumed.best_episode_return == pytest.approx(0.46)


def test_policy_version_check_rejects_mixed_collection_epoch():
    """A barrier epoch cannot silently train on multiple behavior policies."""
    cfg = _config()
    state = _state(cfg)
    first = _transition(state)
    second = _transition(state)
    second.policy_version += 1

    contributions = {0: ([first], 0.0), 1: ([second], 0.0)}

    with pytest.raises(RuntimeError, match="mixed policy versions"):
        _coherent_policy_version(contributions)


@pytest.mark.asyncio
async def test_actor_contributes_only_once_per_collection_epoch():
    """An actor cannot outrun peers by submitting multiple batches under one policy."""
    cfg = _config(actors=1)
    state = _state(cfg)
    queue = asyncio.Queue()
    actor = SynchronousActorClient(0, cfg, state, queue)
    actor.rollout = [_transition(state)]

    await actor._submit_collection_rollout(0.25)
    actor.rollout = [_transition(state)]
    await actor._submit_collection_rollout(0.5)

    actor_id, epoch, rollout, bootstrap = queue.get_nowait()
    assert actor_id == 0
    assert epoch == 0
    assert len(rollout) == 1
    assert bootstrap == pytest.approx(0.25)
    assert queue.empty()

    state.advance_collection_epoch()
    actor._refresh_collection_epoch()
    actor.rollout = [_transition(state)]
    await actor._submit_collection_rollout(0.75)
    assert queue.get_nowait()[1] == 1


@pytest.mark.asyncio
async def test_learner_waits_for_every_actor_before_publishing_next_policy():
    """One actor's rollout cannot trigger a policy publish before its peer arrives."""
    cfg = _config(actors=2)
    state = _state(cfg)
    queue = asyncio.Queue()
    learner = asyncio.create_task(synchronous_learner_loop(cfg, state, queue))

    rollout_a = [_transition(state), _transition(state)]
    rollout_b = [_transition(state), _transition(state)]
    version = state.published_policy_version

    await queue.put((0, 0, rollout_a, 0.0))
    await asyncio.sleep(0)
    assert state.collection_epoch == 0
    assert state.published_policy_version == version

    await queue.put((1, 0, rollout_b, 0.0))
    for _ in range(100):
        if state.collection_epoch == 1:
            break
        await asyncio.sleep(0.01)

    assert state.collection_epoch == 1
    assert state.published_policy_version > version

    learner.cancel()
    with pytest.raises(asyncio.CancelledError):
        await learner
